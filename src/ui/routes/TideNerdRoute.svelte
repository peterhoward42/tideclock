<main class="route tide-nerd-route">
  <h1>Tide Nerd</h1>
  <p class="tide-nerd-route__lede">
  	A playful explanation of how tides work, and what causes them - with respectful nods
	and links to the more serious information. 
  </p>

  <section class="tide-nerd-route__section" aria-labelledby="tide-nerd-pulse-heading">
    <h2 class="tide-nerd-route__h" id="tide-nerd-pulse-heading">Let's start in your bath</h2>
    <p class="tide-nerd-route__p">
		You know that thing when when you push yourself backwards in the bath a bit to
		quickly?  A tidal wave of water gets pushed up behind you and you end up with a wet
		floor. Your wave then travels back the other way, and gradually subsides. The water
		somehow got high enough to spill over the end without you adding any water. 
		You put energy into it which created a short lived lump that travelled initially
		backwards, but then bounces back and gradually settled to flat water again.
    </p>
    <p class="tide-nerd-route__p">
		Tides are more or less the same phenomenon, but working on a somewhat larger body of
		water. Instead of the water in your bath, the water involved is ALL of it in the
		seas and oceans worldwide. And it's the moon's gravity that is creating the shove
		that puts the energy in. This wave takes roughly 6 hours to go one way, and then the
		same to come back the other way.
	</p> 

    <p class="tide-nerd-route__nod">
	  Oceanographers would talk about long-wavelength surface gravity waves and the global
	  tide as a set of standing-wave modes on a rotating planet, not water being poured into
	  your harbour.
    </p>
  </section>

  <section class="tide-nerd-route__section" aria-labelledby="tide-nerd-lumps-heading">
    <h2 class="tide-nerd-route__h" id="tide-nerd-lumps-heading">A pair of bumps
	</h2>
    <p class="tide-nerd-route__p">
		Because all the earth's water is loose and spread out, the moon's gravity pulls it
		into a hump pointing towards the moon. Suprisingly a hump forms on the opposite side
		as well. But that's because the earth itself gets pulled slightly towards the moon,
		and it leaves the water on the far side slightly left behind. So you can think of
		the earth always wearing a pair of ears made of water.
	</p>
    <p class="tide-nerd-route__nod">
	  The paired bulges come from the combined effect of lunar gravitational attraction and
	  the centrifugal tendency of the Earth–Moon system; textbooks draw them as the
	  equilibrium tidal
      ellipse.
    </p>
  </section>

  <section class="tide-nerd-route__section" aria-labelledby="tide-nerd-carousel-heading">
    <h2 class="tide-nerd-route__h" id="tide-nerd-carousel-heading">Those humps  go for a
	stroll</h2>
    <p class="tide-nerd-route__p">
		The moon takes about 28 days to saunter round the earth in its orbit. And the
		water bumps follow it - they stay pointing at wherever the moon has reached. So one
		tidal effect is that the bumps are very slowly creeping round the earth too. But you
		can't sense that from tide motion on any given day because if you watched all day it
		would have moved so few degrees you wouldn't be able to tell. But that movement
		plays its part underneath the faster moving stuff we are going to come on to.
    </p>
    <p class="tide-nerd-route__nod">
      The lunar tide-producing potential rotates with the Moon’s orbital period; the sub-lunar and
      anti-lunar bulges track lunar longitude on the order of a synodic month.
    </p>
  </section>

  <section class="tide-nerd-route__section" aria-labelledby="tide-nerd-spin-heading">
    <h2 class="tide-nerd-route__h" id="tide-nerd-spin-heading">The fast stuff</h2>
    <p class="tide-nerd-route__p">
		The earth spinning on its own axis is belting round. A full turn every 24 hours
		means that if you stand at the equator you are travelling in a circle at round about
		1000mph. A little slower the further you move away from the equator. But those water
		humps are not. This is slightly harder to imagine. The earch is spinning, all the
		water particles are spinning keeping track with it, but the
		<strong>position</strong> of the hump of water stays fixed pointing at wherever the
		moon is. The water particles that make up the hump
		are continuously being changed as the earth spins underneath the humps the humps
		stay put. It's actually the same thing as you see if you look at waves rolling in at
		the beach. The position of the wave is moving towards the beach but it's really
		different parts of the water being lifted up and then let back down as the wave
		passes through. We perceive the tide level rising as the we get dragged into the
		hump by the earth's rotation, and then once we get half way through it and begin to
		be dragged out the other side - we percieve the tide level falling back again.
    </p>
    <p class="tide-nerd-route__nod">
      An observer on Earth experiences the tidal bulges as celestial bodies appear to move westward
      across the sky; the dominant semidiurnal period (~12 h 25 min for the Moon) is a beat between
      lunar orbital motion and Earth’s rotation.
    </p>
  </section>



  <section class="tide-nerd-route__section" aria-labelledby="tide-nerd-dance-heading">
    <h2 class="tide-nerd-route__h" id="tide-nerd-dance-heading">Face each other, hold
	hands and spin round</h2>
    <p class="tide-nerd-route__p">
		The childhood game while facing each other and holding hands you spin round on the
		spot supported by your friend opposite pulling you into the centre. Can you imagine
		what would happen if one of you were quite a bit heavier than than the other? You'd
		both still spin round and round but the heavier person would travel over a smaller
		area than you do. If one of you was huge and the other tiny, the big person would
		only move slightly in a circular motion - whereas you would be more or less flying
		round them. The big person would be pulling you strongly into the centre, but you'd
		only be pulling them a tiny bit. Now the bad news. When you learned at school 
		that the moon orbits the earth they lied just a little bit to keep things simple.
		They implied that the earth stood still. But the real
		truth is that the earth and moon are the heavy friend and the light friend. Sure,
		the moon is being made to belt round the earth, but the earth too is being yanked
		slightly into a circular motion.
    </p>
    <p class="tide-nerd-route__nod">
      The Earth and Moon orbit their common barycentre, which lies inside the Earth but not at its
      centre; tidal theory uses this two-body picture rather than “moon around fixed Earth.”
    </p>
  </section>

  <section class="tide-nerd-route__section" aria-labelledby="tide-nerd-sun-heading">
    <h2 class="tide-nerd-route__h" id="tide-nerd-sun-heading">Here comes the sun</h2>
    <p class="tide-nerd-route__p">
	  No not the Beatles song!

	  It's not so well known that the sun also affects tides. It too has gravity that
	  creates two more water lumps on earth just like the moon. These are smaller than the
	  moon's. But the interesting thing happens as a consequence of the choreography of
	  movement between earth, moon and sun. Sometimes the two sets of bumps line up and that
	  gives us more exaggerated tides. The high tide gets higher and the low tide gets
	  lower. Just as often, but on different weeks, the bumps are at right angles to each
	  other and don't influence each other. The formal name for the exaggerated ones is
	  "Spring" tides. (nothing to do with the season), and the unaffected ones with smaller
	  more modest extremes are called "Neap" tides. You'll hear sea dogs saying "we're on
	  springs at the moment". We experience it as a gradual weekly change, one week of
	  spring tides, then a week of neap tides etc. You can see the planetry alignment that
	  causes these by looking at the moon. Spring tides happen when the the moon is just a
	  thin sliver in the sky and when its a full circle. What you're looking at is the
	  shadow of earth cast onto the sun when all three of the earth, sun and moon are
	  roughly lined up.
    </p>
    <p class="tide-nerd-route__nod">
      Solar and lunar tidal potentials superpose; spring and neap tides follow the beat between the
      principal semi-diurnal lunar and solar constituents (often discussed via M₂ and S₂ in harmonic
      analysis).
    </p>
  </section>

  <section class="tide-nerd-route__section" aria-labelledby="tide-nerd-equinox-heading">
    <h2 class="tide-nerd-route__h" id="tide-nerd-equinox-heading">Those druids were on to
	something</h2>
    <p class="tide-nerd-route__p">
		Druids concluded thousands of years' ago that the sun's equinoxes had a spiritual
		significance. Equinoxes are the events that occur once in March and once in
		September when the Sun passes directly over the earth's equator. They certainly
		affect tides. And that's because the "pull" is more directly inline with the earth
		rather than slightly angled.  Equinoxes create a short-lived additional amplication
		factor on tides. In particular, when they coincide with Spring tides - you get very
		low lows, and very high highs. In Looe - Cornwall (The place the Tide Dial calls
		home) - there's an island that you can sometimes wade out to when this happens. It's
		a bit of local party.
    </p>
    <p class="tide-nerd-route__nod">
      Equinoctial spring tides are the enhanced spring tides near the equinoxes when the solar
      declination is small and the solar tidal component aligns more effectively with many coasts;
      they ride on top of the ordinary spring–neap cycle, not instead of it.
    </p>
  </section>

  <section class="tide-nerd-route__section" aria-labelledby="tide-nerd-pressure-heading">
    <h2 class="tide-nerd-route__h" id="tide-nerd-pressure-heading">The air is a blanket</h2>
    <p class="tide-nerd-route__p">
	  The atmosphere is a fat heavy blanket of air sitting on the sea. When the weather
	  makes the atmospheric
	  pressure lower which usually happens in stormy weather, it slightly lifts the blanket
	  so the sea can stand a bit taller. Which means yet higher tides. 
    </p>
    <p class="tide-nerd-route__nod">
      This is the inverse barometer effect: roughly, about one centimetre of sea-level change per
      hectopascal of atmospheric pressure departure from mean.
    </p>
  </section>

  <section class="tide-nerd-route__section" aria-labelledby="tide-nerd-pressure-heading">
    <h2 class="tide-nerd-route__h" id="tide-nerd-pressure-heading">Wind</h2>
    <p class="tide-nerd-route__p">
	The wind strength and direction makes a small difference too. It has the effect of
	bulldozing some of the water along just like your bum in the bath. It's most noticeable
	when the wind is blowing right into a river estuary or harbour. Here in Looe, we know
	that if all the other factors are telling us that the tide will be high, if we also have
	a strong Easterly wind, it's going to "overtop" the harbour wall and flood the shops in
	the high street. It happens a few times most years.
    </p>
  </section>

  <section class="tide-nerd-route__section" aria-labelledby="tide-nerd-shore-heading">
    <h2 class="tide-nerd-route__h" id="tide-nerd-shore-heading">Wedges and swirls</h2>
    <p class="tide-nerd-route__p">
		When the tide has to rise or fall, a lot of water has got to move, not just up or
		down but also over beaches, up rivers and so on. And it can't happen instantly. It
		flows over those surfaces with friction - like treacle would - only less obviously.
		If the place it's got to flow through gets progressively narrower it banks up trying
		to get through and makes the tide even higher at that spot. A fun way to see that
		happening is to use the tide dial to look at the tides in Portishead in Somerset. It
		sits in the river Severn estuary which forms a huge funnel shape with Wales on the
		other side. You'll see amazingly large tidal height ranges there. (Particularly on
		spring tides). If you'd like to see another really odd one, look at 
		Bournmouth - Dorset. Sometimes you'll see a sort of double wobble around the high
		and low tide times. That one is caused by the movement of the tide in and out of the
		English Channel causing huge but slow "sloshing" patterns.

    </p>
    <p class="tide-nerd-route__nod">
      Coastal engineers separate astronomical tides from meteorological residuals (surge, setup) and
      use local bathymetry in hydrodynamic models; amphidromic systems and quarter-wavelength
      resonances explain why two places on the same chart can disagree.
    </p>
  </section>

