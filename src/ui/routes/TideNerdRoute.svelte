  <h1>Tide Nerd</h1>
  <p class="tide-nerd-route__lede">
    A few cheerful wrong turns on the way to roughly-right ideas about why the sea rises and falls.
    Each bit starts with something you can picture in the bath; a short coda nods to what pedants and
    professionals would call it. This page will grow and the jokes will get better — or worse.
  </p>

  <section class="tide-nerd-route__section" aria-labelledby="tide-nerd-pulse-heading">
    <h2 class="tide-nerd-route__h" id="tide-nerd-pulse-heading">The bath, then the planet</h2>
    <p class="tide-nerd-route__p">
      Slide backwards in a full bath and a wave runs the wrong way, climbs the end, and sometimes
      sloshes over your shoulders. Nothing is “filling up” from a tap — a lump of water travelled
      because you shoved energy into the tub. Now imagine that lump is made of, oh, all the oceans,
      and the shove was the moon’s gravity instead of your bum: a pulse of raised water that has to go
      somewhere, takes its time getting there, and takes its time coming back. At home the trip is
      half a second. Out there it is more like six hours out and six hours back, give or take, which
      is why “high tide” feels like an appointment rather than a splash.
    </p>
    <p class="tide-nerd-route__nod">
      Oceanographers would talk about long-wavelength surface gravity waves and the global tide as a
      set of standing-wave modes on a rotating planet, not water being poured into your harbour.
    </p>
  </section>

  <section class="tide-nerd-route__section" aria-labelledby="tide-nerd-lumps-heading">
    <h2 class="tide-nerd-route__h" id="tide-nerd-lumps-heading">Two lumps on a wet marble</h2>
    <p class="tide-nerd-route__p">
      The moon is nosy. It tugs on anything with mass, and the sea is conveniently loose and spread
      out. So the water piles up where the tug is strongest — a bump under the moon — and, less
      obviously, another bump on the far side, because the solid Earth is being yanked too and the
      water there is comparatively left behind. Two humps on opposite sides of the planet, like
      love handles on a very round athlete.
    </p>
    <p class="tide-nerd-route__nod">
      The paired bulges come from the combined effect of lunar gravitational attraction and the
      centrifugal tendency of the Earth–Moon system; textbooks draw them as the equilibrium tidal
      ellipse.
    </p>
  </section>

  <section class="tide-nerd-route__section" aria-labelledby="tide-nerd-carousel-heading">
    <h2 class="tide-nerd-route__h" id="tide-nerd-carousel-heading">The slow carousel</h2>
    <p class="tide-nerd-route__p">
      Those humps are welded to the moon’s attention. As the moon saunters around us, the humps
      saunter too — one lap in about twenty-eight days. You never sit on the beach thinking “well,
      the lump has moved three degrees since Tuesday,” because twenty-eight days is a glacial parade
      compared with anything you can feel on your ankles.
    </p>
    <p class="tide-nerd-route__nod">
      The lunar tide-producing potential rotates with the Moon’s orbital period; the sub-lunar and
      anti-lunar bulges track lunar longitude on the order of a synodic month.
    </p>
  </section>

  <section class="tide-nerd-route__section" aria-labelledby="tide-nerd-spin-heading">
    <h2 class="tide-nerd-route__h" id="tide-nerd-spin-heading">The fast ride</h2>
    <p class="tide-nerd-route__p">
      Meanwhile the Earth is a show-off and spins once a day. You, the pier, and the chip shop are
      all on the spinning crust, so you are carried into a hump, through it, out the other side, and
      into the next one — like going through a fairground tunnel that only has two high bits. That
      daily rotation is the drumbeat you actually live by.
    </p>
    <p class="tide-nerd-route__nod">
      An observer on Earth experiences the tidal bulges as celestial bodies appear to move westward
      across the sky; the dominant semidiurnal period (~12 h 25 min for the Moon) is a beat between
      lunar orbital motion and Earth’s rotation.
    </p>
  </section>

  <section class="tide-nerd-route__section" aria-labelledby="tide-nerd-local-heading">
    <h2 class="tide-nerd-route__h" id="tide-nerd-local-heading">Why it feels like the sea is coming to you</h2>
    <p class="tide-nerd-route__p">
      From the promenade it looks personal: “the tide is coming in” as if the bay had decided to
      visit. Really you were delivered to the lump by the planet’s spin — the water did not commute
      up the channel like a train, the stage you stand on moved into a taller part of the global
      wobble. Same sea, different height under your wellies because you changed seats on the
      carousel.
    </p>
    <p class="tide-nerd-route__nod">
      Local phase is described by the tidal constituent model at your latitude and longitude; “flood”
      and “ebb” are the time derivative of height at a fixed geographic point, not bulk transport of
      a single body of water up an estuary (though currents do move water, that is a separate story).
    </p>
  </section>

  <section class="tide-nerd-route__section" aria-labelledby="tide-nerd-dance-heading">
    <h2 class="tide-nerd-route__h" id="tide-nerd-dance-heading">Two partners, one wobble</h2>
    <p class="tide-nerd-route__p">
      We say the moon orbits the Earth as if the Earth were a dignified anchor and the moon a polite
      satellite. Gravity is ruder than that: both bodies pull each other. Mostly the Earth sits in
      the middle and the moon loops the outside, but the Earth also traces a tiny circle — a wobble
      around a point between them. That is why the “two humps a day” story hangs together instead of
      feeling like a coincidence: you are on a planet that is both spinning and being tugged in a
      double act.
    </p>
    <p class="tide-nerd-route__nod">
      The Earth and Moon orbit their common barycentre, which lies inside the Earth but not at its
      centre; tidal theory uses this two-body picture rather than “moon around fixed Earth.”
    </p>
  </section>

  <section class="tide-nerd-route__section" aria-labelledby="tide-nerd-sun-heading">
    <h2 class="tide-nerd-route__h" id="tide-nerd-sun-heading">The sun elbows in</h2>
    <p class="tide-nerd-route__p">
      The sun watches this monthly soap opera and wants a line. It has its own gravity — enough to
      keep us on a yearly lap — and it adds a smaller, second set of humps. When sun and moon line
      up with us, their tugs gang up: big tides, the springs. When they pull at cross purposes, the
      humps are shallower: neaps. The rhythm repeats on a roughly fortnightly beat, which is why
      “spring tide week” and “neap tide week” are a recurring coastal mood, not a one-off.
    </p>
    <p class="tide-nerd-route__nod">
      Solar and lunar tidal potentials superpose; spring and neap tides follow the beat between the
      principal semi-diurnal lunar and solar constituents (often discussed via M₂ and S₂ in harmonic
      analysis).
    </p>
  </section>

  <section class="tide-nerd-route__section" aria-labelledby="tide-nerd-equinox-heading">
    <h2 class="tide-nerd-route__h" id="tide-nerd-equinox-heading">Equinox enthusiasm</h2>
    <p class="tide-nerd-route__p">
      Twice a year the sun crosses the equator and, for a moment, day and night pretend to be equals.
      Around those weeks the sun’s tidal shove lines up more neatly with places that are not being
      cheeky about latitude, and spring tides can pack an extra punch — the “equinoctial” grumble you
      hear in harbours when someone’s pontoon looks a few inches more offended than usual. At Looe,
      on one or two days a year, you can walk across to Looe Island knee-deep at low water; the town
      treats it as a bit of a festival rather than a geology lecture.
    </p>
    <p class="tide-nerd-route__nod">
      Equinoctial spring tides are the enhanced spring tides near the equinoxes when the solar
      declination is small and the solar tidal component aligns more effectively with many coasts;
      they ride on top of the ordinary spring–neap cycle, not instead of it.
    </p>
  </section>

  <section class="tide-nerd-route__section" aria-labelledby="tide-nerd-pressure-heading">
    <h2 class="tide-nerd-route__h" id="tide-nerd-pressure-heading">The air also pushes</h2>
    <p class="tide-nerd-route__p">
      The atmosphere is a fat blanket of air sitting on the sea. High pressure is like an extra
      hand pressing down: the sea is squashed a little lower than the tables promised. Low pressure
      lifts the blanket and the water can stand a bit taller. Storms almost always bring low
      pressure, so wind and “extra height” often arrive together — not two separate misfortunes that
      happen to coincide. At Looe, the harbour can overtop and flood a few shops when strong
      easterlies, a deep low, and a spring tide line up; each piece is modest on its own, miserable
      in combination.
    </p>
    <p class="tide-nerd-route__nod">
      This is the inverse barometer effect: roughly, about one centimetre of sea-level change per
      hectopascal of atmospheric pressure departure from mean, before dynamic wind setup is
      considered.
    </p>
  </section>

  <section class="tide-nerd-route__section" aria-labelledby="tide-nerd-shore-heading">
    <h2 class="tide-nerd-route__h" id="tide-nerd-shore-heading">Wind, cliffs, and teacup harbours</h2>
    <p class="tide-nerd-route__p">
      Wind stacks water against coasts when it blows the same way for long enough; a narrow funnel of
      a harbour sloshes like a shaken cup; a wide bay yawns and delays everything. The astronomical
      tide is the metronome, but your beach is an instrument with its own shape — channels, sandbars,
      and headlands all conducting the same note differently. If you want a concrete comparison, set
      the dial to Portishead and look at its tidal range next to your own place: same moon, very
      different cup.
    </p>
    <p class="tide-nerd-route__nod">
      Coastal engineers separate astronomical tides from meteorological residuals (surge, setup) and
      use local bathymetry in hydrodynamic models; amphidromic systems and quarter-wavelength
      resonances explain why two places on the same chart can disagree.
    </p>
  </section>

  <section class="tide-nerd-route__section" aria-labelledby="tide-nerd-eddy-heading">
    <h2 class="tide-nerd-route__h" id="tide-nerd-eddy-heading">Giant swirls far away</h2>
    <p class="tide-nerd-route__p">
      The ocean is not a bathtub with one plughole. At huge scales water is steered in great slow
      loops, with odd corners where the tide barely moves — and other places where the same lunar shove is
      amplified or delayed because water has been steered around an entire sea. Folk on the south
      coast of England sometimes raise an eyebrow when Bournemouth behaves differently from a chart
      tuned to Scotland: part of that is the North Sea and its shelves acting like a very large,
      very slow piece of plumbing upstream.
    </p>
    <p class="tide-nerd-route__nod">
      Real tides are described by the Laplace tidal equations on a rotating Earth with coastlines;
      solutions show amphidromic points (nodes) and cotidal lines, and large shallow seas such as the
      North Sea dominate the UK’s along-shore phase and range patterns.
    </p>
  </section>
